    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();

if(row == -1){
    JOptionPane.showMessageDialog(this, "Select a row first");
    return;
}

int id = Integer.parseInt(jTable1.getValueAt(row, 0).toString());

String currentName = jTable1.getValueAt(row, 1).toString();
String currentAge = jTable1.getValueAt(row, 2).toString();
String currentGender = jTable1.getValueAt(row, 3).toString();
String currentDisease = jTable1.getValueAt(row, 4).toString();

// take input from user
String name = JOptionPane.showInputDialog(this, "Enter Name:", currentName);
String ageStr = JOptionPane.showInputDialog(this, "Enter Age:", currentAge);
String gender = JOptionPane.showInputDialog(this, "Enter Gender:", currentGender);
String disease = JOptionPane.showInputDialog(this, "Enter Disease:", currentDisease);

if(name == null || ageStr == null || gender == null || disease == null) return;

int confirm = JOptionPane.showConfirmDialog(this, "Update this record?");
if(confirm != 0) return;

try {
    Connection con = DriverManager.getConnection(
        "jdbc:mysql://localhost:3306/hospital","root","1234"
    );

    String query = "UPDATE patients SET name=?, age=?, gender=?, disease=? WHERE patient_id=?";
    PreparedStatement pst = con.prepareStatement(query);

    pst.setString(1, name.trim());
    pst.setInt(2, Integer.parseInt(ageStr.trim()));
    pst.setString(3, gender.trim());
    pst.setString(4, disease.trim());
    pst.setInt(5, id);

    pst.executeUpdate();

    JOptionPane.showMessageDialog(this, "Updated successfully");

    loadTable();

    con.close();

} catch(Exception e){
    e.printStackTrace();
}
    }//GEN-LAST:event_jButton2ActionPerformed

