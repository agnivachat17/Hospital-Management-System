    public void loadTable() {
    try {
        Class.forName("com.mysql.cj.jdbc.Driver");
        Connection con = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/hospital","root","1234"
        );

        String query = "SELECT * FROM patients";
        PreparedStatement pst = con.prepareStatement(query);
        ResultSet rs = pst.executeQuery();

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        while(rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("patient_id"),
                rs.getString("name"),
                rs.getInt("age"),
                rs.getString("gender"),
                rs.getString("disease")
            });
        }
        jTable1.getColumnModel().getColumn(0).setPreferredWidth(50);  // ID
        jTable1.getColumnModel().getColumn(1).setPreferredWidth(150); // Name
        jTable1.getColumnModel().getColumn(2).setPreferredWidth(50);  // Age
        jTable1.getColumnModel().getColumn(3).setPreferredWidth(100); // Gender
        jTable1.getColumnModel().getColumn(4).setPreferredWidth(120); // Disease
        con.close();
    } catch(Exception e) {
        e.printStackTrace();
    }
}

